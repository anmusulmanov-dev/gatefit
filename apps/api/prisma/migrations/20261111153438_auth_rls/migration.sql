-- ---------------------------------------------------------------------------
-- sessions, otp_codes
-- ---------------------------------------------------------------------------

ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON sessions
  USING (organization_id = app_current_org())
  WITH CHECK (organization_id = app_current_org());

ALTER TABLE otp_codes ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON otp_codes
  USING (organization_id = app_current_org())
  WITH CHECK (organization_id = app_current_org());

GRANT SELECT, INSERT, UPDATE ON sessions, otp_codes TO gatefit_app;

-- ---------------------------------------------------------------------------
-- users: closed to the API role
-- ---------------------------------------------------------------------------
-- users is global identity, shared by all organizations. The API may read only the
-- non-secret columns of users linked to the current organization (through staff or a
-- session). Everything else goes through the SECURITY DEFINER functions below, which look
-- up exactly one phone at a time, so the table cannot be listed or scraped.

REVOKE ALL ON users FROM gatefit_app;
GRANT SELECT (id, phone, email, created_at, updated_at, deleted_at) ON users TO gatefit_app;

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_linked_users ON users FOR SELECT USING (
  EXISTS (
    SELECT 1 FROM staff s
    WHERE s.user_id = users.id AND s.organization_id = app_current_org()
  )
  OR EXISTS (
    SELECT 1 FROM sessions se
    WHERE se.user_id = users.id AND se.organization_id = app_current_org()
  )
);

-- ---------------------------------------------------------------------------
-- Auth functions
-- ---------------------------------------------------------------------------
-- Owned by gatefit_migrator, so they run outside RLS. Each does one narrow thing.

-- Maps a subdomain to its organization. Called before any tenant context exists.
CREATE FUNCTION auth_resolve_organization(p_slug text)
  RETURNS TABLE (id uuid, status organization_status, locale text)
  LANGUAGE sql STABLE SECURITY DEFINER
  SET search_path = public, pg_temp
  AS $$
    SELECT o.id, o.status, o.locale
    FROM organizations o
    WHERE o.slug = p_slug AND o.deleted_at IS NULL
  $$;

-- Credentials of one active staff member of the current organization, found by phone or
-- by user id (exactly one of the two is given). Returns no row for anyone else.
CREATE FUNCTION auth_staff_credentials(p_phone text, p_user_id uuid)
  RETURNS TABLE (
    user_id uuid,
    staff_id uuid,
    password_hash text,
    totp_secret text,
    role_name text,
    role_is_system boolean
  )
  LANGUAGE sql STABLE SECURITY DEFINER
  SET search_path = public, pg_temp
  AS $$
    SELECT u.id, s.id, u.password_hash, u.totp_secret, r.name, r.is_system
    FROM users u
    JOIN staff s ON s.user_id = u.id AND s.organization_id = app_current_org()
    JOIN roles r ON r.id = s.role_id AND r.organization_id = s.organization_id
    WHERE ((p_phone IS NOT NULL AND u.phone = p_phone) OR (p_user_id IS NOT NULL AND u.id = p_user_id))
      AND u.deleted_at IS NULL
      AND s.deleted_at IS NULL
      AND s.status = 'active'
      AND r.deleted_at IS NULL
  $$;

-- First-time TOTP enrolment for a staff member of the current organization. Never
-- overwrites an existing secret: resetting a second factor is a platform operation.
CREATE FUNCTION auth_enroll_totp(p_user_id uuid, p_secret text)
  RETURNS boolean
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = public, pg_temp
  AS $$
BEGIN
  UPDATE users u
  SET totp_secret = p_secret, updated_at = now()
  WHERE u.id = p_user_id
    AND u.totp_secret IS NULL
    AND u.deleted_at IS NULL
    AND EXISTS (
      SELECT 1 FROM staff s
      WHERE s.user_id = u.id
        AND s.organization_id = app_current_org()
        AND s.deleted_at IS NULL
        AND s.status = 'active'
    );
  RETURN FOUND;
END;
$$;

-- Returns the user that owns a phone, creating it on first sign-in. p_id is the id to
-- use for a new row (UUID v7, generated by the API). NULL for a deleted user.
CREATE FUNCTION auth_find_or_create_user(p_id uuid, p_phone text)
  RETURNS uuid
  LANGUAGE plpgsql SECURITY DEFINER
  SET search_path = public, pg_temp
  AS $$
DECLARE
  found_id uuid;
BEGIN
  IF app_current_org() IS NULL THEN
    RAISE EXCEPTION 'auth_find_or_create_user requires a tenant context';
  END IF;

  INSERT INTO users (id, phone, updated_at)
  VALUES (p_id, p_phone, now())
  ON CONFLICT (phone) DO NOTHING;

  SELECT u.id INTO found_id FROM users u WHERE u.phone = p_phone AND u.deleted_at IS NULL;
  RETURN found_id;
END;
$$;

REVOKE ALL ON FUNCTION auth_resolve_organization(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION auth_staff_credentials(text, uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION auth_enroll_totp(uuid, text) FROM PUBLIC;
REVOKE ALL ON FUNCTION auth_find_or_create_user(uuid, text) FROM PUBLIC;

GRANT EXECUTE ON FUNCTION auth_resolve_organization(text) TO gatefit_app;
GRANT EXECUTE ON FUNCTION auth_staff_credentials(text, uuid) TO gatefit_app;
GRANT EXECUTE ON FUNCTION auth_enroll_totp(uuid, text) TO gatefit_app;
GRANT EXECUTE ON FUNCTION auth_find_or_create_user(uuid, text) TO gatefit_app;
